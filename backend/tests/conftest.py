"""Shared test fixtures.

Every test runs against a throwaway data directory with its own SQLite file, so tests never
touch a real corpus and never depend on each other's state. The whole suite is offline: the
``mock`` provider stands in for every network call, which is also what lets the app be clicked
through before the user has an API key.
"""

from __future__ import annotations

import shutil
import subprocess
import tempfile
from collections.abc import Iterator
from pathlib import Path

import pytest

from quicklearn import settings as settings_module
from quicklearn.config import Config, set_config
from quicklearn.db import session as session_module
from quicklearn.db.bootstrap import init_database


@pytest.fixture
def data_dir() -> Iterator[Path]:
    path = Path(tempfile.mkdtemp(prefix="quicklearn-test-"))
    try:
        yield path
    finally:
        session_module.dispose_engine()
        shutil.rmtree(path, ignore_errors=True)


@pytest.fixture
def config(data_dir: Path) -> Iterator[Config]:
    cfg = Config(data_dir=data_dir, worker_concurrency=2)
    set_config(cfg)
    settings_module.reset_settings()
    init_database(cfg)
    try:
        yield cfg
    finally:
        session_module.dispose_engine()
        settings_module.reset_settings()


@pytest.fixture
def store(config: Config) -> settings_module.SettingsStore:
    """Settings store wired to the temp database, with the mock provider selected."""
    s = settings_module.get_settings()
    s.set_many(
        {
            "routing.fast": {"provider": "mock", "model": "mock-fast"},
            "routing.standard": {"provider": "mock", "model": "mock-standard"},
            "routing.deep": {"provider": "mock", "model": "mock-deep"},
            "stt.provider": "mock",
            "stt.model": "mock-stt",
            "tts.provider": "mock",
            "embedding.provider": "mock",
        }
    )
    return s


def _have_ffmpeg() -> bool:
    try:
        subprocess.run(["ffmpeg", "-version"], capture_output=True, check=True, timeout=20)
        return True
    except Exception:
        return False


HAVE_FFMPEG = _have_ffmpeg()
requires_ffmpeg = pytest.mark.skipif(not HAVE_FFMPEG, reason="ffmpeg not on PATH")


@pytest.fixture
def wav_file(data_dir: Path) -> Path:
    """A real, tiny WAV file generated by ffmpeg.

    Fixtures are generated rather than committed as binaries so the repo stays diffable and the
    test is exercising a genuinely decodable file rather than bytes someone hand-rolled.
    """
    if not HAVE_FFMPEG:
        pytest.skip("ffmpeg not on PATH")
    out = data_dir / "tone.wav"
    subprocess.run(
        [
            "ffmpeg",
            "-hide_banner",
            "-loglevel",
            "error",
            "-y",
            "-f",
            "lavfi",
            "-i",
            "sine=frequency=440:duration=3",
            "-ar",
            "44100",
            "-ac",
            "2",
            str(out),
        ],
        check=True,
        capture_output=True,
        timeout=60,
    )
    return out


